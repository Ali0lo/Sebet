export type TranslationSchema = typeof translations.az;
export type TranslationDictionary = TranslationSchema;

export function normalizeLanguage(lang: string | undefined | null): Language {
  if (lang === "ru" || lang === "rus") return "ru";
  if (lang === "en" || lang === "eng") return "en";
  return "az";
}

export function useTranslation(): { t: TranslationSchema; language: Language } {
  const rawLang = useSebEtStore((state) => state.language);
  const language = normalizeLanguage(rawLang);
  const t: TranslationSchema = (translations[language] || translations.az) as TranslationSchema;
  return { t, language };
}

/**
 * Helper to translate category names dynamically from backend models
 */
export function getTranslatedCategoryName(
  slugOrName: string,
  t: TranslationSchema
): string {
  const s = (slugOrName || "").toLowerCase();
  if (s.includes("dairy") || s.includes("sud") || s.includes("süd") || s.includes("agarti") || s.includes("ağartı")) {
    return t.categoriesList.dairy;
  }
  if (s.includes("meat") || s.includes("et") || s.includes("ət") || s.includes("toyuq")) {
    return t.categoriesList.meat;
  }
  if (s.includes("bakery") || s.includes("corek") || s.includes("çörək") || s.includes("un")) {
    return t.categoriesList.bakery;
  }
  if (s.includes("produce") || s.includes("meyve") || s.includes("meyvə") || s.includes("terevez") || s.includes("tərəvəz")) {
    return t.categoriesList.produce;
  }
  if (s.includes("staples") || s.includes("erzaq") || s.includes("ərzaq") || s.includes("yag") || s.includes("yağ") || s.includes("quru")) {
    return t.categoriesList.staples;
  }
  if (s.includes("tea") || s.includes("cay") || s.includes("çay") || s.includes("qehve") || s.includes("qəhvə") || s.includes("coffee")) {
    return t.categoriesList.teaCoffee;
  }
  if (s.includes("sweet") || s.includes("sirniyyat") || s.includes("şirniyyat") || s.includes("qelyanalti") || s.includes("qəlyanaltı")) {
    return t.categoriesList.sweets;
  }
  if (s.includes("drink") || s.includes("icki") || s.includes("içki") || s.includes("su") || s.includes("beverage")) {
    return t.categoriesList.drinks;
  }
  if (s.includes("clean") || s.includes("temizlik") || s.includes("təmizlik") || s.includes("yuyucu")) {
    return t.categoriesList.cleaning;
  }
  if (s.includes("care") || s.includes("qulluq") || s.includes("gigiyena") || s.includes("sexsi") || s.includes("şəxsi")) {
    return t.categoriesList.care;
  }
  return slugOrName;
}
